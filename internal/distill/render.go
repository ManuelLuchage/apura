package distill

import (
	"fmt"
	"os"
	"strings"

	"github.com/ManuelLuchage/apura/internal/core"
	"github.com/ManuelLuchage/apura/internal/shell"
)

// Doc is everything a renderer needs.
type Doc struct {
	Session      core.Session
	SessionNotes []core.Note
	Result       Result
	Shell        shell.Integration
}

// tildify replaces the home directory with ~ for readability and portability.
func tildify(dir string) string {
	if home, err := os.UserHomeDir(); err == nil && home != "" {
		if dir == home {
			return "~"
		}
		if strings.HasPrefix(dir, home+"/") {
			return "~" + dir[len(home):]
		}
	}
	return dir
}

// cdArg renders a directory for a cd line, keeping ~ unquoted so it expands
// and quoting only when the path has characters a shell would interpret.
func cdArg(sh shell.Integration, dir string) string {
	t := tildify(dir)
	quote := func(p string) string {
		if isPlainPath(p) {
			return p
		}
		return sh.Quote(p)
	}
	if t == "~" {
		return "~"
	}
	if strings.HasPrefix(t, "~/") {
		return "~/" + quote(t[2:])
	}
	return quote(t)
}

func isPlainPath(p string) bool {
	if p == "" {
		return false
	}
	for _, r := range p {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("/._-+,@", r)) {
			return false
		}
	}
	return true
}

// RenderMarkdown produces a human runbook.
func RenderMarkdown(d Doc) string {
	var b strings.Builder
	s := d.Session
	fmt.Fprintf(&b, "# %s\n\n", s.Name)
	if s.Goal != "" {
		fmt.Fprintf(&b, "> %s\n\n", s.Goal)
	}
	var meta []string
	if len(s.Tags) > 0 {
		meta = append(meta, "**Tags:** "+strings.Join(s.Tags, ", "))
	}
	if len(s.Techs) > 0 {
		meta = append(meta, "**Technologies:** "+strings.Join(s.Techs, ", "))
	}
	meta = append(meta, "**Shell:** "+d.Shell.Name())
	fmt.Fprintf(&b, "%s\n\n", strings.Join(meta, " · "))

	for _, n := range d.SessionNotes {
		if n.StepID == nil {
			fmt.Fprintf(&b, "- %s\n", n.Body)
		}
	}
	if len(d.SessionNotes) > 0 {
		b.WriteString("\n")
	}

	b.WriteString("## Steps\n\n")
	if len(d.Result.Steps) == 0 {
		b.WriteString("_No successful steps._\n")
	}
	lastDir := ""
	for i, st := range d.Result.Steps {
		fmt.Fprintf(&b, "%d. ", i+1)
		if st.Cwd != "" && st.Cwd != lastDir {
			fmt.Fprintf(&b, "In `%s`:\n", tildify(st.Cwd))
			lastDir = st.Cwd
		} else {
			b.WriteString("\n")
		}
		for _, n := range st.Notes {
			fmt.Fprintf(&b, "   %s\n", n.Body)
		}
		fmt.Fprintf(&b, "   ```%s\n", d.Shell.FenceLang())
		for _, line := range strings.Split(st.Command, "\n") {
			fmt.Fprintf(&b, "   %s\n", line)
		}
		b.WriteString("   ```\n\n")
	}

	if len(d.Result.Dropped) > 0 {
		counts := map[string]int{}
		for _, x := range d.Result.Dropped {
			counts[x.Rule]++
		}
		fmt.Fprintf(&b, "<sub>Distilled by apura: %d of %d steps removed (failed/skipped: %d, noise: %d, repeated: %d).</sub>\n",
			len(d.Result.Dropped), len(d.Result.Dropped)+len(d.Result.Steps),
			counts["unsuccessful"], counts["noise"], counts["repeat"])
	}
	return b.String()
}

// RenderScript produces an executable script for the session's shell.
func RenderScript(d Doc) string {
	var b strings.Builder
	sh := d.Shell
	b.WriteString(sh.ScriptHeader() + "\n")
	fmt.Fprintf(&b, "# %s\n", d.Session.Name)
	if d.Session.Goal != "" {
		fmt.Fprintf(&b, "# %s\n", d.Session.Goal)
	}
	b.WriteString("# Generated by apura distill — review before running.\n\n")
	guard := sh.StepGuard()
	lastDir := ""
	for i, st := range d.Result.Steps {
		fmt.Fprintf(&b, "# [%d]", i+1)
		for _, n := range st.Notes {
			fmt.Fprintf(&b, " %s", strings.ReplaceAll(n.Body, "\n", " "))
		}
		b.WriteString("\n")
		if st.Cwd != "" && st.Cwd != lastDir {
			fmt.Fprintf(&b, "cd %s\n", cdArg(sh, st.Cwd))
			if guard != "" {
				b.WriteString(guard + "\n")
			}
			lastDir = st.Cwd
		}
		b.WriteString(st.Command + "\n")
		if guard != "" {
			b.WriteString(guard + "\n")
		}
		b.WriteString("\n")
	}
	return b.String()
}
